// bindAllEnv registers a MOMUS_* environment variable for every config key so
// that viper.Unmarshal (which uses mapstructure and does not consult
// AutomaticEnv) still honors environment variables.
func bindAllEnv() error {
	v := reflect.ValueOf(&config{}).Elem()
	t := v.Type()
	for i := 0; i < t.NumField(); i++ {
		key := t.Field(i).Tag.Get("mapstructure")
		if key == "" {
			continue
		}
		if err := viper.BindEnv(key); err != nil {
			return fmt.Errorf("bind env var for %s: %w", key, err)
		}
	}
	return nil
}

// captureFlagValues records the current cfg field value for every field whose
// CLI flag was explicitly set on the command line. These values must survive
// viper.Unmarshal so that CLI flags take precedence over the config file.
func captureFlagValues(cfg *config, cmd *cobra.Command) map[int]reflect.Value {
	captured := make(map[int]reflect.Value)
	v := reflect.ValueOf(cfg).Elem()
	t := v.Type()
	for i := 0; i < v.NumField(); i++ {
		tag := t.Field(i).Tag.Get("flag")
		if tag == "" {
			continue
		}
		for _, name := range strings.Split(tag, ",") {
			if flagChanged(cmd, name) {
				captured[i] = reflect.ValueOf(v.Field(i).Interface())
				break
			}
		}
	}
	return captured
}

func restoreExplicitFlagValues(cfg *config, captured map[int]reflect.Value) {
	v := reflect.ValueOf(cfg).Elem()
	for i, val := range captured {
		v.Field(i).Set(val)
	}
}

// flagChanged reports whether the named flag was explicitly set anywhere in the
// command chain (local flags and inherited persistent flags from ancestors).
func flagChanged(cmd *cobra.Command, name string) bool {
	for c := cmd; c != nil; c = c.Parent() {
		if c.Flags().Changed(name) || c.PersistentFlags().Changed(name) {
			return true
		}
	}
	return false
}
