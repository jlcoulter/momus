// initializeViper wires viper into the config used by a command. It sets up
// config file discovery and environment variable binding, reads the config
// file, and merges values into cfg with the following precedence (highest
// first):
//
//  1. explicitly-set CLI flags
//  2. environment variables (MOMUS_ prefix)
//  3. config file (--config path, ./momus.toml, or ~/.momus/config.toml)
//  4. flag defaults (already applied to cfg by cobra)
//
// CLI flags are bound directly to cfg fields by cobra, so this function must
// not let viper clobber values the user set explicitly on the command line.
// It snapshots those fields before unmarshaling and restores them afterwards.
func initializeViper(cfg *config, cmd *cobra.Command) error {
	explicit := captureFlagValues(cfg, cmd)
	if err := configureViper(cfg); err != nil {
		return err
	}
	if err := viper.ReadInConfig(); err != nil {
		if _, ok := err.(viper.ConfigFileNotFoundError); !ok {
			return fmt.Errorf("read config file: %w", err)
		}
		// Config file not found; defaults and CLI flags still apply.
	}
	if err := viper.Unmarshal(cfg); err != nil {
		return fmt.Errorf("parse config: %w", err)
	}
	restoreExplicitFlagValues(cfg, explicit)
	return nil
}

// userConfigPath is the per-user config file (relative to $HOME) that is
// auto-initialised with a placeholder template on first run.
const userConfigPath = ".momus/config.toml"

// configureViper sets up viper and resolves which config file to load.
//
// Precedence (highest first):
//  1. the --config flag path
//  2. ./momus.toml in the working directory
//  3. $HOME/.momus/config.toml (auto-initialised on first run if missing)
//
// Environment variables (MOMUS_ prefix) and CLI flags remain the highest and
// lowest priority sources respectively, on top of whatever config file is
// loaded.
func configureViper(cfg *config) error {
	// Environment variable binding applies regardless of where the config file
	// lives. AutomaticEnv alone is not consulted by viper.Unmarshal, so each
	// key is explicitly bound to its MOMUS_* variable.
	viper.SetEnvPrefix("MOMUS")
	viper.SetEnvKeyReplacer(strings.NewReplacer("-", "_"))
	viper.AutomaticEnv()

	switch {
	case cfg.ConfigFile != "":
		viper.SetConfigFile(cfg.ConfigFile)
	case fileExists("momus.toml"):
		viper.SetConfigFile("momus.toml")
	default:
		homeConfig := home.ConfigPath()
		if err := ensureHomeConfig(homeConfig); err != nil {
			return err
		}
		viper.SetConfigFile(homeConfig)
	}

	return bindAllEnv()
}

// fileExists reports whether path exists and is a regular file.
func fileExists(path string) bool {
	fi, err := os.Stat(path)
	return err == nil && !fi.IsDir()
}

// ensureHomeConfig creates $HOME/.momus/config.toml with placeholder content
// when it does not yet exist.
func ensureHomeConfig(path string) error {
	if fileExists(path) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return fmt.Errorf("create config dir %s: %w", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, []byte(homeConfigTemplate), 0o600); err != nil {
		return fmt.Errorf("write home config %s: %w", path, err)
	}
	return nil
}

